#!/bin/sh
# ?????? UTF-8 ??? *.java ???????? GBK ??????
tmp=".git/utf8-check-list"
git diff --cached --name-only --diff-filter=ACM -- '*.java' > "$tmp" 2>/dev/null
status=0
while IFS= read -r f; do
  [ -n "$f" ] || continue
  [ -f "$f" ] || continue
  if ! iconv -f UTF-8 -t UTF-8 "$f" >/dev/null 2>&1; then
    echo ""
    echo "[pre-commit] ???? UTF-8 ??? Java ????????:"
    echo "             $f"
    echo "?? UTF-8 ? BOM ??????????? ANSI/GBK ????"
    status=1
  fi
done < "$tmp"
rm -f "$tmp"
exit $status

