    def others = wordList.findAll { it.meaning != entry.meaning }.take(3)
    if (others.size() >= 2) {
        def options = [entry.meaning] + others.collect { it.meaning }
        java.util.Collections.shuffle(options)
        questions << collector.choice("单词\"${entry.word}\"的中文意思是？", options,
                options.indexOf(entry.meaning), "CET词汇：${entry.word} 的释义为 ${entry.meaning}")
    }
    // 汉译英填空
    questions << collector.fill("汉译英：${entry.meaning} —— ______。", entry.word,
            "CET词汇：${entry.word} = ${entry.meaning}")
}

