package com.chua.common.support.constant;

/**
 * 数值常量接口
 * <p>
 * 包含系统中常用的数值常量，避免魔法数字的直接使用。
 * </p>
 *
 * @author CH
 */
public interface NumberConstant {

    /**
     * 零值
     */
    int ZERO = 0;

    /**
     * 一
     */
    int ONE = 1;

    /**
     * 二
     */
    int TWO = 2;

    /**
     * 三
     */
    int THREE = 3;

    /**
     * 四
     */
    int FOUR = 4;

    /**
     * 五
     */
    int FIVE = 5;

    /**
     * 六
     */
    int SIX = 6;

    /**
     * 七
     */
    int SEVEN = 7;

    /**
     * 八
     */
    int EIGHT = 8;

    /**
     * 九
     */
    int NINE = 9;

    /**
     * 十
     */
    int TEN = 10;

    /**
     * 十二
     */
    int TWELVE = 12;

    /**
     * 二十四
     */
    int TWENTY_FOUR = 24;

    /**
     * 六十
     */
    int SIXTY = 60;

    /**
     * 一百
     */
    int ONE_HUNDRED = 100;

    /**
     * 一千
     */
    int ONE_THOUSAND = 1000;

    /**
     * 1024 (2^10)
     */
    int KB = 1024;

    /**
     * 1024^2 (1M)
     */
    int MB = 1048576;

    /**
     * 1024^3 (1G)
     */
    int GB = 1073741824;

    /**
     * 常用数值 1000
     */
    int NUMBER_1000 = 1000;

    /**
     * 常用数值 10000
     */
    int NUMBER_10000 = 10000;

    /**
     * 最大 int 值
     */
    int MAX_INT = Integer.MAX_VALUE;

    /**
     * 最小 int 值
     */
    int MIN_INT = Integer.MIN_VALUE;

    /**
     * 最大 long 值
     */
    long MAX_LONG = Long.MAX_VALUE;

    /**
     * 最小 long 值
     */
    long MIN_LONG = Long.MIN_VALUE;

    /**
     * π 近似值
     */
    double PI = Math.PI;

    /**
     * 欧拉常数 e 近似值
     */
    double E = Math.E;
}