package com.chua.common.support.geo;

/**
 * 城市地理信息
 *
 * @author CH
 * @since 4.0.0
 */
public class GeoCity {

    /**
     * 城市名称
     */
    private String city;

    /**
     * 获取城市名称
     *
     * @return 城市名称
     */
    public String getCity() {
        return city;
    }

    /**
     * 设置城市名称
     *
     * @param city 城市名称
     */
    public void setCity(String city) {
        this.city = city;
    }
}
