-- =====================================================================
-- V6.4__drop_ai_service_token.sql
-- 通道: 结构清理（退役表）
-- 说明: 服务实例与网关统一按 AppKey（sys_ai_app_key）鉴权后，
--       sys_ai_service_token 不再签发、不再校验、也不再有任何读写代码。
--       留着一张没人读写的表只会让后来的人以为「还有两条凭证链路」，
--       所以直接删除。
--
-- 为什么不再兼容：
--   1) 同一把 AppKey 在网关 /v2/v1/* 与实例端口 /v1/* 通用，凭证只有一本账；
--   2) 模型范围（分组 ∩ 限定模型）、次数 / Token / 余额配额、用量归集都在 Key 上，
--      老表里的 model_ids / quota_type / used_* 已无判定入口；
--   3) 项目仍在开发阶段，无存量调用方需要平滑迁移。
--
-- 幂等：DROP TABLE IF EXISTS，重复执行与全新库都安全。
-- =====================================================================

DROP TABLE IF EXISTS `sys_ai_service_token`;
